def soma():
    print("Fazendo uma soma")
    numero1 = int(input("Número 1: "))
    numero2 = int(input("Número 2: "))
    return print(numero1 + numero2)

def subtracao():
    print("Fazendo uma subtracao")
    numero1 = int(input("Número 1: "))
    numero2 = int(input("Número 2: "))
    return print(numero1 - numero2)

def olaUsuario(nome, idade):
    print(f"Olá {nome}")
    print(f"Sua idade : {idade}")

